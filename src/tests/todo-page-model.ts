import assert from "node:assert/strict";
import { JSDOM } from "jsdom";
import { TFolder } from "obsidian";
import { todoPageRecords, TodoPageView } from "../home/todo-page";
import { EchoInkTodoFormModal } from "../home/todo-edit-modal";
import { renderTodoTable, todoTableCopy } from "../home/todo-table";
import type { ParsedTodoRecord } from "../home/todo-markdown";

export async function runTodoPageModelTests(): Promise<void> {
  const dom = new JSDOM("<body><main></main></body>", { pretendToBeVisual: true });
  const win = dom.window;
  Object.assign(globalThis, { window: win, document: win.document, HTMLElement: win.HTMLElement });
  const proto = win.HTMLElement.prototype as any;
  proto.empty = function () { this.replaceChildren(); };
  proto.setText = function (text: string) { this.textContent = text; };
  proto.addClass = function (...names: string[]) { this.classList.add(...names); };
  proto.setAttr = function (name: string, value: string) { this.setAttribute(name, value); };
  proto.createEl = function (tag: string, options: any = {}) {
    const element = this.ownerDocument.createElement(tag);
    if (options.cls) element.className = options.cls;
    if (options.text) element.textContent = options.text;
    if (options.value !== undefined) element.value = options.value;
    for (const [key, value] of Object.entries(options.attr ?? {})) element.setAttribute(key, String(value));
    this.appendChild(element); return element;
  };
  proto.createDiv = function (options: any = {}) { return this.createEl("div", options); };
  proto.createSpan = function (options: any = {}) { return this.createEl("span", options); };
  const folder = (path: string, children: TFolder[] = []) => Object.assign(new TFolder(), { path, name: path.split("/").at(-1), children });
  const root = folder("Projects", [folder("Projects/EchoInk"), folder("Projects/Other")]);
  const vaultListeners = new Map<string, Set<(...args: any[]) => void>>();
  const emitVault = (name: string, ...args: any[]) => { for (const callback of [...vaultListeners.get(name) ?? []]) callback(...args); };
  const app: any = { vault: { on: (name: string, callback: (...args: any[]) => void) => {
    const listeners = vaultListeners.get(name) ?? new Set(); listeners.add(callback); vaultListeners.set(name, listeners); return { name, callback };
  }, getAbstractFileByPath: (path: string) => [root, ...root.children].find(file => file.path === path), offref(event: any) { vaultListeners.get(event.name)?.delete(event.callback); } }, keymap: { pushScope() {}, popScope() {} }, scope: {} };
  const records: ParsedTodoRecord[] = Array.from({ length: 45 }, (_, index) => ({ id: `todo-${index}`, title: `事项 ${index}`, people: "方哥, Alice", categoryName: index < 23 ? "工作" : "生活", project: index < 23 ? "EchoInk" : "Other", dueDate: index === 3 ? "2026-01-01" : "", dueTime: index === 3 ? "09:30" : undefined, done: index === 0, lineStart: index, lineEnd: index, extraMetaLines: [] }));
  const projects = root.children.map((entry: any) => ({ path: entry.path, name: entry.name, rootPath: root.path, parentPath: root.path, label: entry.name, value: entry.name }));
  const filters = { status: "all" as const, category: null, project: null, page: 1 };
  const first = todoPageRecords(records, projects, filters);
  assert.equal(first.records.length, 20); assert.equal(first.records[0].id, "todo-3"); assert.equal(first.pages, 3);
  const filtered = todoPageRecords(records, projects, { ...filters, project: "path:Projects/EchoInk", page: 2 });
  assert.equal(filtered.total, 23); assert.equal(filtered.records.length, 3); assert.equal(filtered.records.at(-1)!.id, "todo-0");
  assert.equal(todoPageRecords(records, projects, { ...filters, status: "done", page: 99 }).page, 1);
  const orphan = { ...records[0], project: "Deleted" };
  assert.equal(todoPageRecords([orphan], projects, { ...filters, project: "raw:Deleted" }).total, 1);
  const storeListeners = new Set<() => void>();
  const store: any = { subscribe: (listener: () => void) => { storeListeners.add(listener); return () => storeListeners.delete(listener); }, snapshot: () => records, initialize: async () => {}, completionStatistics: () => ({ total: 5, today: 2, unknown: 1, activity: [{ date: "2026-01-01", count: 4 }] }) };
  let handoffs = 0, handoffText = "", patch: any, fail = false;
  let reads = 0, readFailure = false;
  store.reload = async () => { reads++; if (readFailure) throw new Error("读取失败"); };
  store.updateTodo = async (_target: any, values: any) => { patch = values; if (fail) throw new Error("文件冲突"); };
  const plugin: any = { app, settings: { settingsLanguage: "zh-CN", todoCategories: [{ id: "work", name: "工作" }], knowledgeBase: { folderBindings: { roles: { projects: { enabled: true, readPaths: ["Projects"] } } } }, agentRegistry: { agents: [{ id: "sol", name: "总助" }], moduleOwners: { todos: "sol" } } }, getTodoStore: () => store, saveSettings: async () => {}, openAgentTaskList: async (_id: string, text: string) => { handoffs++; handoffText = text; return true; } };
  const view: any = new TodoPageView({} as any, plugin);
  Object.assign(view, { app, contentEl: win.document.querySelector("main"), closed: false, initialized: true });
  view.renderShell(); view.renderData();
  assert.equal(view.field("list").querySelectorAll("thead th").length, 7);
  assert.equal(view.field("list").querySelectorAll("tbody tr").length, 20);
  assert.equal(view.field("list").querySelector(".echoink-todo-action-delete").classList.contains("echoink-delete-button"), true);
  assert.equal(view.field("list").querySelector(".echoink-todo-action-edit").classList.contains("echoink-delete-button"), false);
  const completionHistory = JSON.stringify(store.completionStatistics());
  assert.equal(view.contentEl.querySelector(".todo-history-panel, .activity-heatmap, [data-todo-page=statistics]"), null);
  assert.match(view.field("count").textContent, /累计完成 5 · 今日完成 2/);
  view.changeFilter({ project: "path:Projects/EchoInk", category: "工作" });
  assert.match(view.field("count").textContent, /累计完成 5 · 今日完成 2/, "Filters do not narrow lifetime completion counts");
  assert.equal(JSON.stringify(store.completionStatistics()), completionHistory, "Removing the visualization keeps historical completion data");
  assert.ok(!view.contentEl.textContent.includes("完成日期未知"));
  assert.ok(view.field("count").textContent.includes("23")); assert.equal(handoffs, 0);
  await view.handoff(); assert.equal(handoffs, 1); assert.match(handoffText, /EchoInk/); assert.match(handoffText, /工作/);
  const wrap = view.field("list").querySelector(".echoink-todo-table-wrap"); wrap.scrollTop = 75; wrap.scrollLeft = 30; wrap.onscroll(); view.renderList();
  assert.equal(view.field("list").querySelector(".echoink-todo-table-wrap").scrollTop, 75);
  view.changeFilter({ status: "open" }); assert.equal(view.state.page, 1); assert.equal(view.state.scrollTop, 0);
  const mobile = win.document.createElement("div"); mobile.classList.add("echoink-mobile");
  let mobileDeletes = 0; renderTodoTable(mobile, [orphan], todoTableCopy("zh-CN"), { onToggle() {}, onEdit() {}, onDelete() { mobileDeletes++; } });
  assert.equal(mobile.querySelectorAll("th").length, 6, "Legacy/mobile callers retain six columns");
  const mobileDelete = mobile.querySelector<HTMLButtonElement>(".echoink-todo-action-delete")!;
  assert.equal(mobileDelete.classList.contains("echoink-delete-button"), false, "the shared mobile table retains its existing delete icon");
  mobileDelete.click(); assert.equal(mobileDeletes, 1, "presentation does not change the original callback");
  const modal: any = new EchoInkTodoFormModal(app, plugin, orphan); modal.open();
  const projectSelect = modal.contentEl.querySelector('[aria-label="项目"]') as HTMLSelectElement;
  assert.match(projectSelect.selectedOptions[0].textContent!, /Deleted/);
  await modal.save(); assert.equal(Object.hasOwn(patch, "project"), false, "Unrelated edits retain invalid raw project association");
  const failure: any = new EchoInkTodoFormModal(app, plugin, records[3]); failure.open();
  const title = failure.contentEl.querySelector('[aria-label="事项"]') as HTMLInputElement;
  title.value = "保留草稿"; title.oninput!(new win.Event("input") as any);
  const select = failure.contentEl.querySelector('[aria-label="项目"]') as HTMLSelectElement;
  select.value = "Projects/Other"; select.onchange!(new win.Event("change") as any);
  fail = true; await failure.save(); assert.equal(title.value, "保留草稿"); assert.equal(select.value, "Projects/Other"); assert.equal(failure.saving, false); assert.equal(patch.project, "Other");
  fail = false; root.children = root.children.filter(child => child.path !== "Projects/Other"); await failure.save();
  assert.equal(failure.saving, false); assert.equal(title.value, "保留草稿", "Project disappearing at submission retains draft");
  failure.close();
  readFailure = true; await view.refresh();
  assert.equal(view.field("data").hidden, true, "Failed reload hides cached actions instead of presenting stale data as fresh");
  assert.match(view.field("status").textContent, /尚未更新/); assert.equal(reads, 1);
  readFailure = false; await view.refresh();
  assert.equal(view.field("data").hidden, false); assert.equal(view.field("status").textContent, ""); assert.equal(reads, 2);
  view.state.page = 2; view.renderList();
  await view.onClose();
  const reopened: any = new TodoPageView({} as any, plugin);
  assert.equal(reopened.state.page, 2, "Reopening retains the last page and filters");
  assert.equal(reopened.state.project, "path:Projects/EchoInk");
  // Dispatch actual subscribed page events, keeping source association
  // rewriting asynchronous as in EchoInkTodoStore's rename listener.
  const renameView: any = new TodoPageView({} as any, plugin);
  Object.assign(renameView, { app, contentEl: win.document.body.createDiv(), closed: false, initialized: true });
  renameView.renderShell(); renameView.renderData(); renameView.attachListeners();
  renameView.changeFilter({ status: "all", category: null, project: "path:Projects/EchoInk" });
  const renamedProject = root.children.find(child => child.path === "Projects/EchoInk")!;
  renamedProject.path = "Projects/Beta"; renamedProject.name = "Beta";
  emitVault("rename", renamedProject, "Projects/EchoInk");
  assert.equal(renameView.state.project, "path:Projects/Beta", "Project rename maps the selected path before source rewrite");
  records.forEach(record => { if (record.project === "EchoInk") record.project = "Beta"; });
  storeListeners.forEach(listener => listener());
  assert.ok(renameView.field("count").textContent.includes("符合条件 23 项"));
  assert.equal(renameView.field("list").querySelectorAll("tbody tr").length, 20);
  root.path = "Work"; renamedProject.path = "Work/Beta";
  emitVault("rename", root, "Projects");
  assert.equal(renameView.state.project, "path:Work/Beta", "Root rename rebases the selected descendant path");
  plugin.settings.knowledgeBase.folderBindings.roles.projects.readPaths = ["Work"];
  storeListeners.forEach(listener => listener());
  assert.ok(renameView.field("count").textContent.includes("符合条件 23 项"));
  assert.equal(renameView.field("toolbar").querySelector<HTMLSelectElement>('[aria-label="项目"]')!.value, "path:Work/Beta");
  await renameView.onClose();
  assert.equal(storeListeners.size, 0); assert.equal([...vaultListeners.values()].reduce((count, listeners) => count + listeners.size, 0), 0);
  console.log("To-do page model: pagination/filtering, seven/six columns, inline completion counts and retained history, handoff scope, scroll, invalid association and save failures passed");
}
