export async function runFinanceFreshMobileBaselineTest() {
  const files = new Map<string, string>();
  const adapter: any = { exists: async (p: string) => files.has(p), read: async (p: string) => { if (!files.has(p)) throw Object.assign(new Error("missing"), { code: "ENOENT" }); return files.get(p)!; },
    write: async (p: string, v: string) => { files.set(p, v); }, mkdir: async () => {}, remove: async (p: string) => { files.delete(p); }, rename: async (a: string, b: string) => { if (files.has(b)) throw new Error("exists"); files.set(b, files.get(a)!); files.delete(a); } };
  const file = "data/lifestyle.json";
  files.set(file, JSON.stringify({ version: 1, budgets: [], financeDefaultBudget: { totalCents: 10000, allocations: {} } }));
  const store = mobileLifestyleStore(adapter, file); await store.initialize();
  const external = JSON.stringify({ version: 1, budgets: [], financeDefaultBudget: { totalCents: 20000, allocations: {} }, external: { keep: true } }); files.set(file, external);
  await assert.rejects(store.updateFresh(() => { throw new Error("stale_version"); }), /stale_version/);
  await assert.rejects(store.update(d => { d.reports = []; }), /已变化/);
  assert.equal(files.get(file), external, "failed fresh validation never advances UI baseline A to externally changed B");
  await store.updateFresh(d => { d.financeDefaultBudget!.allocations.餐饮 = 5000; });
  assert.equal(JSON.parse(files.get(file)!).external.keep, true, "explicit fresh CAS compares and installs using the same B baseline");
  console.log("PASS mobile fresh-candidate/committed-baseline isolation after failed validation and successful fresh replacement");
}
