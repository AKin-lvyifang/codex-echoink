export async function financeOperationsFixture(root: string) {
  const fixture = await nativeJournalFixture(root);
  fixture.plugin.settings.lifestyle.finance.enabled = true;
  fixture.plugin.settings.lifestyle.finance.categories.push({ name: "住宿", aliases: [], iconId: "bed", active: true });
  fixture.plugin.registerEvent = () => {};
  (fixture.app.vault as any).on = () => ({});
  (fixture.app.fileManager as any).processFrontMatter = async (file: any, change: (fields: Record<string, unknown>) => void) => fixture.app.vault.process(file, markdown => {
    const match = markdown.match(/^---\n([\s\S]*?)\n---\n/u)!;
    const fields = parse(match[1]); change(fields);
    return `---\n${stringify(fields)}---\n${markdown.slice(match[0].length)}`;
  });
  (fixture.app.fileManager as any).trashFile = async (file: { path: string }) => {
    await mkdir(path.join(root, ".trash"), { recursive: true });
    await rename(path.join(root, file.path), path.join(root, ".trash", path.basename(file.path)));
  };
  const storePath = path.join(root, ".finance-store.json");
  const store = new LifestyleStore(storePath); await store.initialize();
  const service = new LifestyleFinanceService({ plugin: fixture.plugin, store, refresh() {} } as any, paidTestAccess);
  return { ...fixture, store, storePath, service };
}
