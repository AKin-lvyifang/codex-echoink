结构和篇幅随证据变化，不机械凑章节、图表或标签。同一组数字保留一种主要核对呈现；已选分类或预算表后，正文只解释用途原因和影响，不重列全部表格行；同内容图按需取舍。前后变化已在总览解释时，不另开重复章节。调整情景集中在结尾，不在正文另写一套下月注意，也不同时罗列同一问题的全部替代方案。新旧Markdown都保持概要、正文、核对依据、提醒与动作的阅读层次。颜色、表头、标签与间距由渲染器实现；Skill只输出受支持的结构及Markdown，不输出任意HTML/CSS。

