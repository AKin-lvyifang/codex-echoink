- 每章title用简洁名词短语，由界面呈现有色标题。正文用text的短段解释原因和影响，关键判断和金额适度加粗；并列原因用短Markdown列表，精确区分各项口径。
- 预算额度、净支出与实际超额，或前后变化需要逐项核对时，选用可用的本地事实table。表内状态标签由程序事实生成，报告解释其影响。图表按证据需要选择chart，解释紧邻图表，不用图装饰段落。
